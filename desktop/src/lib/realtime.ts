/**
 * Voice Session Client Integration (OpenAI Realtime WebRTC & Google Gemini Live WebSocket)
 */

export interface VoiceSessionResponse {
  provider?: 'openai' | 'gemini';
  client_secret?: string;
  ws_url?: string;
  expires_at: number;
  session_id: string;
  model: string;
  voice: string;
  switched_to_fallback?: boolean;
  fallback_reason?: string;
}

const BACKEND_URL = 'http://127.0.0.1:8000';

/**
 * Request ephemeral voice session credentials from local FastAPI backend.
 * Never requests or exposes permanent API keys.
 */
export async function fetchVoiceSession(): Promise<VoiceSessionResponse> {
  const response = await fetch(`${BACKEND_URL}/api/voice/session`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Accept': 'application/json',
    },
    body: JSON.stringify({}),
  });

  if (!response.ok) {
    let errorDetail = `HTTP ${response.status}`;
    try {
      const errJson = await response.json();
      if (errJson?.error?.message) {
        errorDetail = errJson.error.message;
      }
    } catch {
      // Ignore JSON parse error on non-JSON response
    }
    throw new Error(`Failed to initialize voice session: ${errorDetail}`);
  }

  return response.json();
}

export interface RealtimeConnection {
  provider?: 'openai' | 'gemini';
  pc?: RTCPeerConnection;
  dc?: RTCDataChannel;
  ws?: WebSocket;
  localStream: MediaStream;
  audioEl?: HTMLAudioElement;
  close?: () => void;
  sendText?: (text: string) => void;
  interrupt?: () => void;
}

/**
 * Establish a direct WebRTC peer connection to OpenAI Realtime gateway
 * using the temporary client_secret generated by the backend.
 */
export async function createRealtimePeerConnection(
  session: VoiceSessionResponse,
  onRemoteTrack?: (stream: MediaStream) => void
): Promise<RealtimeConnection> {
  const pc = new RTCPeerConnection({
    iceServers: [{ urls: 'stun:stun.l.google.com:19302' }],
  });

  const audioEl = new Audio();
  audioEl.autoplay = true;

  pc.ontrack = (event) => {
    audioEl.srcObject = event.streams[0];
    onRemoteTrack?.(event.streams[0]);
  };

  const localStream = await navigator.mediaDevices.getUserMedia({
    audio: {
      echoCancellation: true,
      noiseSuppression: true,
      autoGainControl: true,
    },
  });

  localStream.getTracks().forEach((track) => {
    pc.addTrack(track, localStream);
  });

  const dc = pc.createDataChannel('oai-events');

  const offer = await pc.createOffer();
  await pc.setLocalDescription(offer);

  const baseUrl = 'https://api.openai.com/v1/realtime';
  const model = session.model || 'gpt-realtime-mini';
  const sdpResponse = await fetch(`${baseUrl}?model=${encodeURIComponent(model)}`, {
    method: 'POST',
    body: offer.sdp,
    headers: {
      'Authorization': `Bearer ${session.client_secret}`,
      'Content-Type': 'application/sdp',
    },
  });

  if (!sdpResponse.ok) {
    const errorText = await sdpResponse.text().catch(() => '');
    localStream.getTracks().forEach((t) => t.stop());
    pc.close();
    throw new Error(
      `OpenAI WebRTC SDP handshake failed (HTTP ${sdpResponse.status}): ${errorText}`
    );
  }

  const answerSdp = await sdpResponse.text();
  const answer: RTCSessionDescriptionInit = {
    type: 'answer',
    sdp: answerSdp,
  };

  await pc.setRemoteDescription(answer);

  return {
    provider: 'openai',
    pc,
    dc,
    localStream,
    audioEl,
    close: () => {
      localStream.getTracks().forEach((t) => t.stop());
      try {
        if (dc.readyState === 'open' || dc.readyState === 'connecting') dc.close();
      } catch {
        // ignore
      }
      pc.close();
      audioEl.srcObject = null;
    },
    sendText: (text: string) => {
      if (dc.readyState === 'open') {
        dc.send(
          JSON.stringify({
            type: 'conversation.item.create',
            item: {
              type: 'message',
              role: 'user',
              content: [{ type: 'input_text', text }],
            },
          })
        );
      }
    },
    interrupt: () => {
      if (dc.readyState === 'open') {
        dc.send(JSON.stringify({ type: 'response.cancel' }));
      }
    },
  };
}

/**
 * Establish a robust, real-time voice & speech connection to Google Gemini Live Bridge.
 */
export async function createGeminiLiveConnection(
  session: VoiceSessionResponse,
  handlers: {
    onOpen?: () => void;
    onMessage?: (data: Record<string, unknown>) => void;
    onError?: (error: Error) => void;
    onClose?: () => void;
  }
): Promise<RealtimeConnection> {
  // 1. Acquire microphone stream
  const localStream = await navigator.mediaDevices.getUserMedia({
    audio: {
      echoCancellation: true,
      noiseSuppression: true,
      autoGainControl: true,
    },
  });

  // 2. Open WebSocket to backend Gemini live bridge
  const wsUrl = session.ws_url
    ? (session.ws_url.startsWith('ws')
        ? session.ws_url
        : `ws://127.0.0.1:8000${session.ws_url}`)
    : 'ws://127.0.0.1:8000/api/voice/gemini-live';

  const ws = new WebSocket(wsUrl);

  // 3. Web Speech Recognition for real-time speech capture
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const SpeechRecognitionClass =
    (window as unknown as { SpeechRecognition?: any; webkitSpeechRecognition?: any }).SpeechRecognition ||
    (window as unknown as { webkitSpeechRecognition?: any }).webkitSpeechRecognition;

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let recognition: any = null;
  let isRecognitionActive = false;

  const startRecognition = () => {
    if (!SpeechRecognitionClass || isRecognitionActive) return;
    try {
      recognition = new SpeechRecognitionClass();
      recognition.continuous = true;
      recognition.interimResults = true;
      recognition.lang = 'en-US';

      recognition.onstart = () => {
        isRecognitionActive = true;
        handlers.onMessage?.({ type: 'input_audio_buffer.speech_started' });
      };

      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      recognition.onresult = (event: any) => {
        let finalTranscript = '';
        for (let i = event.resultIndex; i < event.results.length; ++i) {
          if (event.results[i].isFinal) {
            finalTranscript += event.results[i][0].transcript;
          }
        }
        finalTranscript = finalTranscript.trim();
        if (finalTranscript && ws.readyState === WebSocket.OPEN) {
          handlers.onMessage?.({ type: 'user_transcript', text: finalTranscript });
          handlers.onMessage?.({ type: 'input_audio_buffer.speech_stopped' });
          ws.send(JSON.stringify({ type: 'conversation.item.create', text: finalTranscript }));
        }
      };

      recognition.onerror = () => {
        // Non-blocking
      };

      recognition.onend = () => {
        isRecognitionActive = false;
        // Keep listening as long as WS is open
        if (ws.readyState === WebSocket.OPEN) {
          try {
            recognition.start();
          } catch {
            // ignore
          }
        }
      };

      recognition.start();
    } catch {
      // Non-blocking in headless / unsupported environments
    }
  };

  // 4. Speech Synthesis for JARVIS spoken voice
  let accumulatedSpeech = '';

  const speakJarvisResponse = (text: string) => {
    if (typeof window === 'undefined' || !window.speechSynthesis) return;

    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(text);
    utterance.rate = 1.0;
    utterance.pitch = 0.95;

    // Pick a natural British or English voice for JARVIS persona
    const voices = window.speechSynthesis.getVoices();
    const preferredVoice = voices.find(
      (v) =>
        v.name.includes('George') ||
        v.name.includes('Natural') ||
        v.name.includes('Ryan') ||
        v.name.includes('Daniel') ||
        v.lang.startsWith('en')
    );
    if (preferredVoice) utterance.voice = preferredVoice;

    utterance.onstart = () => {
      handlers.onMessage?.({ type: 'response.audio.delta', isSpeaking: true });
    };

    utterance.onend = () => {
      handlers.onMessage?.({ type: 'response.audio.done', isSpeaking: false });
    };

    utterance.onerror = () => {
      handlers.onMessage?.({ type: 'response.audio.done', isSpeaking: false });
    };

    window.speechSynthesis.speak(utterance);
  };

  ws.onopen = () => {
    handlers.onOpen?.();
    startRecognition();
  };

  ws.onmessage = (event) => {
    try {
      const data = JSON.parse(event.data);

      if (data.type === 'response.audio_transcript.delta' && data.delta) {
        accumulatedSpeech += data.delta;
      } else if (data.type === 'response.done') {
        const toSpeak = accumulatedSpeech.trim() || (data.text as string) || '';
        accumulatedSpeech = '';
        data.text = toSpeak;
        if (toSpeak) {
          speakJarvisResponse(toSpeak);
        }
      }

      handlers.onMessage?.(data);
    } catch {
      // ignore
    }
  };

  ws.onerror = () => {
    handlers.onError?.(new Error('Gemini voice bridge connection error'));
  };

  ws.onclose = () => {
    if (recognition) {
      try {
        recognition.stop();
      } catch {
        // ignore
      }
    }
    handlers.onClose?.();
  };

  return {
    provider: 'gemini',
    ws,
    localStream,
    close: () => {
      localStream.getTracks().forEach((t) => t.stop());
      if (typeof window !== 'undefined' && window.speechSynthesis) {
        window.speechSynthesis.cancel();
      }
      if (recognition) {
        try {
          recognition.abort();
        } catch {
          // ignore
        }
      }
      if (ws.readyState === WebSocket.OPEN || ws.readyState === WebSocket.CONNECTING) {
        ws.close();
      }
    },
    sendText: (text: string) => {
      if (ws.readyState === WebSocket.OPEN) {
        ws.send(JSON.stringify({ type: 'conversation.item.create', text }));
      }
    },
    interrupt: () => {
      if (typeof window !== 'undefined' && window.speechSynthesis) {
        window.speechSynthesis.cancel();
      }
      if (ws.readyState === WebSocket.OPEN) {
        ws.send(JSON.stringify({ type: 'response.cancel' }));
      }
    },
  };
}

export default {
  fetchVoiceSession,
  createRealtimePeerConnection,
  createGeminiLiveConnection,
};
